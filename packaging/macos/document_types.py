#!/usr/bin/env python3
"""Fill photo document types from the engine's import extension list.

Run with Info.plist.in to refresh the checked-in template. package.sh also runs this
on the assembled plist. The Rust plist test checks against the compiled EXTENSIONS.
"""
import pathlib
import plistlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
# Use the system's identifiers where macOS defines them. Imported declarations supply
# filename tags on older releases; they never export ownership of another vendor's type.
TYPES = {
    "jpg": "public.jpeg", "jpeg": "public.jpeg", "png": "public.png",
    "tif": "public.tiff", "tiff": "public.tiff", "webp": "org.webmproject.webp",
    "dng": "com.adobe.raw-image", "cr2": "com.canon.cr2-raw-image",
    "cr3": "com.canon.cr3-raw-image", "nef": "com.nikon.raw-image",
    "nrw": "com.nikon.nrw-raw-image", "arw": "com.sony.arw-raw-image",
    "raf": "com.fuji.raw-image", "orf": "com.olympus.raw-image",
    "rw2": "com.panasonic.rw2-raw-image", "rwl": "com.leica.rwl-raw-image",
    "raw": "com.panasonic.raw-image", "pef": "com.pentax.raw-image",
    "srw": "com.samsung.raw-image", "psd": "com.adobe.photoshop-image",
    "jxl": "public.jpeg-xl", "gif": "com.compuserve.gif", "bmp": "com.microsoft.bmp",
    "heic": "public.heic", "heif": "public.heif", "avif": "public.avif",
    "iiq": "com.phaseone.raw-image", "crw": "com.canon.crw-raw-image",
    "mrw": "com.konicaminolta.raw-image", "mos": "com.leafamerica.raw-image",
    "erf": "com.epson.raw-image", "3fr": "com.hasselblad.3fr-raw-image",
    "fff": "com.hasselblad.fff-raw-image",
}
RASTER = {"jpg", "jpeg", "png", "tif", "tiff", "webp", "psd", "jxl", "gif", "bmp", "heic", "heif", "avif"}


def declarations():
    source = (ROOT / "crates/engine/src/import.rs").read_text()
    source = re.sub(r"//[^\n]*", "", source)
    match = re.search(r"pub const EXTENSIONS:.*?=\s*&\[(.*?)\];", source, re.S)
    if match is None:
        raise ValueError("Cannot find the engine's EXTENSIONS; update the generator")
    extensions = re.findall(r'"([a-z0-9]+)"', match.group(1))
    if not extensions or len(set(extensions)) != len(extensions):
        raise ValueError("The engine's EXTENSIONS must be nonempty and unique")
    grouped = {}
    for ext in extensions:
        uti = TYPES.get(ext, f"ai.storyteller.lightcraft.image.{ext}")
        grouped.setdefault(uti, []).append(ext)
    documents = [{
        "CFBundleTypeName": "Photographs",
        "CFBundleTypeRole": "Editor",
        "LSHandlerRank": "Alternate",
        "CFBundleTypeExtensions": extensions,
        "LSItemContentTypes": list(grouped),
    }]
    imported = [{
        "UTTypeIdentifier": uti,
        "UTTypeDescription": f"{exts[0].upper()} image",
        "UTTypeConformsTo": ["public.data", "public.image" if exts[0] in RASTER else "public.camera-raw-image"],
        "UTTypeTagSpecification": {"public.filename-extension": exts},
    } for uti, exts in grouped.items()]
    return documents, imported


def main():
    path = pathlib.Path(sys.argv[1])
    data = plistlib.loads(path.read_bytes())
    data["CFBundleDocumentTypes"], data["UTImportedTypeDeclarations"] = declarations()
    xml = plistlib.dumps(data, sort_keys=False)
    header = b"<!-- Document types are generated by packaging/macos/document_types.py from engine EXTENSIONS. -->\n"
    path.write_bytes(xml.replace(b"<!DOCTYPE", header + b"<!DOCTYPE", 1))


if __name__ == "__main__":
    main()
